#!/usr/bin/env python3
"""The libultra signature databases and hooks/policy.json as C tables for cartscan/sigs.c, and the _h_ symbol table
for harness/tload.c: gen_sigdb.py OUT.c [HOOKTAB.c]"""
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DBS = [os.path.join(HERE, "..", "hooks", "patch_symbols.inl"),  # Daedalus's libultra signatures
       os.path.join(HERE, "..", "hooks", "libultra_extra.inl"),  # generated from libultra objects
       os.path.join(HERE, "..", "hooks", "libultra_rom.inl"),
       os.path.join(HERE, "..", "hooks", "libgultra.inl"),  # 2.0I libgultra_rom from ultralib, KMC GCC 2.7.2
       os.path.join(HERE, "..", "hooks", "libultra_L.inl")]  # 2.0L IDO libultra (non-ROM) from ultralib
POLICY = os.path.join(HERE, "..", "hooks", "policy.json")
XREF = re.compile(r"PATCH_XREF_(FUNCTION|VAR_HI|VAR_LO)\((\d+),\s*(\w+)\)")
SIG = re.compile(r"PATCH_SIGNATURE_LIST_ENTRY\((\w+),\s*(\d+),\s*(\d+),\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\)")
KIND = {"FUNCTION": "SR_FUNCTION", "VAR_HI": "SR_VAR_HI", "VAR_LO": "SR_VAR_LO"}


def parse_db(path):
    """{symbol: [(numops, firstop, partial, crc, [(offset, kind, target)])]} and the variable names."""
    xrefs, sigs, cur, variables = {}, collections.defaultdict(list), None, set()
    for line in open(path):
        m = re.match(r"\s*BEGIN_PATCH_XREFS\((\w+)\)", line)
        if m:
            cur = xrefs.setdefault(m.group(1), [])
            continue
        m = re.match(r"\s*BEGIN_PATCH_SIGNATURE_LIST\((\w+)\)", line)
        if m:
            cur, sym = None, m.group(1)
            continue
        m = XREF.search(line)
        if m and cur is not None:
            cur.append((int(m.group(2)), m.group(1), m.group(3)))
            if m.group(1) != "FUNCTION":
                variables.add(m.group(3))
            continue
        m = SIG.search(line)
        if m:
            label = m.group(1)
            sigs[sym].append((int(m.group(2)), int(m.group(3)), int(m.group(4), 16), int(m.group(5), 16),
                              sorted(xrefs.get(label, []))))
    return dict(sigs), variables


def main():
    out_path = sys.argv[1]
    sigs = {}
    for path in DBS:
        s, _ = parse_db(path)
        for name, variants in s.items():
            sigs.setdefault(name, []).extend(variants)
    names, ids = [], {}

    def nid(n):
        if n not in ids:
            ids[n] = len(names)
            names.append(n)
        return ids[n]

    for name in sigs:
        nid(name)
    syms, variants, refs = [], [], []
    for name, vs in sigs.items():
        syms.append((nid(name), len(variants), len(vs), int(any(not v[4] for v in vs))))
        for numops, firstop, partial, crc, xr in vs:
            by_off = {off: (kind, tgt) for off, kind, tgt in xr}
            variants.append((numops, firstop, partial, crc, len(refs), len(by_off)))
            refs += [(off, KIND[kind], nid(tgt)) for off, (kind, tgt) in sorted(by_off.items())]
    by_first = [[] for _ in range(64)]
    for si, (name, vs) in enumerate(sigs.items()):
        for v in vs:
            by_first[v[1]].append(si)
    policy = json.load(open(POLICY))
    sym_of = [-1] * len(names)
    for si, s in enumerate(syms):
        sym_of[s[0]] = si
    o = ['// Generated by tools/gen_sigdb.py from the signature databases and hooks/policy.json', '#include "sigs.h"', ""]
    o.append(f"const uint16_t sig_nnames = {len(names)}, sig_nsyms = {len(syms)}, pol_n = {len(policy)};")
    o.append("const char *const sig_names[] = {" + ", ".join(json.dumps(n) for n in names) + "};")
    o.append("const int16_t sig_sym_of[] = {" + ", ".join(map(str, sym_of)) + "};")
    o.append("const SigSym sig_syms[] = {" + ", ".join("{%d, %d, %d, %d}" % s for s in syms) + "};")
    o.append("const SigVar sig_vars[] = {" + ", ".join(
        "{%d, %d, %d, %d, 0x%08Xu, 0x%08Xu}" % (n, r0, nr, fo, p, c) for n, fo, p, c, r0, nr in variants) + "};")
    o.append("const SigRef sig_refs[] = {" + (", ".join("{%d, %d, %s}" % (off, t, k) for off, k, t in refs) or "{0}")
             + "};")
    starts, flat = [], []
    for lst in by_first:
        starts.append(len(flat))
        flat += lst
    starts.append(len(flat))
    o.append("const uint16_t sig_first_start[65] = {" + ", ".join(map(str, starts)) + "};")
    o.append("const uint16_t sig_first_list[] = {" + (", ".join(map(str, flat)) or "0") + "};")
    o.append("const char *const pol_names[] = {" + ", ".join(json.dumps(n) for n in policy) + "};")
    o.append("const char *const pol_hooks[] = {" + ", ".join(json.dumps(h) for h in policy.values()) + "};")
    open(out_path, "w").write("\n".join(o) + "\n")
    if len(sys.argv) > 2:
        hooks = sorted({h for h in policy.values() if h not in ("noop", "unsupported")})
        t = ['// Generated by tools/gen_sigdb.py from hooks/policy.json', '#include "tload.h"', ""]
        t += [f"void h_{h}(void);" for h in hooks]
        t.append(f"const unsigned t_nhook_syms = {len(hooks)};")
        t.append("const TSym t_hook_syms[] = {" + ", ".join(f'{{"_h_{h}", (void *)h_{h}}}' for h in hooks) + "};")
        open(sys.argv[2], "w").write("\n".join(t) + "\n")


if __name__ == "__main__":
    main()
